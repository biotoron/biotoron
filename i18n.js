  var keys = Object.keys(D).sort(function (a, b) { return b.length - a.length; });
  var AR = "\\u0621-\\u063A\\u0641-\\u064A\\u064B-\\u065F\\u0671-\\u06D3";
  function esc(s) { return s.replace(/[.*+?^${}()|[\]\\\/]/g, "\\$&"); }
  var re = new RegExp("(?<![" + AR + "])(?:" + keys.map(esc).join("|") + ")(?![" + AR + "])", "g");
  var hasAr = /[؀-ۿ]/;

  function tr(s) {
    if (lang === "ar" || s == null || !hasAr.test(s)) return s;
    RULES.forEach(function (r) { s = s.replace(r[0], r[1]); });
    if (!hasAr.test(s)) return s;
    return s.replace(re, function (m) { return D[m]; });
  }

  var ATTRS = ["placeholder", "title", "value", "data-confirm", "aria-label", "alt"];
  function fix(node) {
    if (node.nodeType === 3) { var v = node.nodeValue; if (hasAr.test(v)) { var t = tr(v); if (t !== v) node.nodeValue = t; } return; }
    if (node.nodeType !== 1) return;
    if (node.tagName === "SCRIPT" || node.tagName === "STYLE" || node.tagName === "TEXTAREA") return;
    ATTRS.forEach(function (a) {
      if (a === "value" && !(node.tagName === "INPUT" && (node.type === "button" || node.type === "submit"))) return;
      var v = node.getAttribute && node.getAttribute(a);
      if (v && hasAr.test(v)) { var t = tr(v); if (t !== v) node.setAttribute(a, t); }
    });
    for (var c = node.firstChild; c; c = c.nextSibling) fix(c);
  }

